function playNextName() {

    if (!isPlayingAll) {
        return;
    }

    if (playAllIndex >= names.length) {

        isPlayingAll = false;
        playAllIndex = 0;

        return;
    }

    const name = names[playAllIndex];

    currentAudio = new Audio("audio/" + name.audio);

    currentAudio.play().catch(() => {

        isPlayingAll = false;
        playAllIndex = 0;

        alert("Audio file not Available.");
    });

    currentAudio.addEventListener("ended", () => {

        if (!isPlayingAll) {
            return;
        }

        playAllIndex++;

        playNextName();
    });
}


